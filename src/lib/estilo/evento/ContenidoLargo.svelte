<p>
	La Jornada Inventada de Cuerdas es un encuentro de práctica y aprendizaje para todes, con o sin
	experiencia. Este texto es de ejemplo: sirve para ver cómo queda la página cuando el evento tiene
	mucho para contar.
</p>
<p>
	Vamos a trabajar en grupos chicos, con foco en el <strong>consentimiento</strong>, los
	<strong>cuidados</strong> y la comunicación. Traé ropa cómoda y, si tenés, tus cuerdas. Si no tenés,
	te prestamos.
</p>
<h2 id="bloque-1">Bloque 1: amarres básicos</h2>
<p>
	Arrancamos con nudos simples y con cómo revisar la circulación. Les facilitadores van a pasar por
	cada grupo.
</p>
<ul>
	<li>15:00 ARG · 15:00 UY · 13:00 COL</li>
	<li>Duración: 1 hora y media</li>
</ul>
<h3>Persona de Prueba Dos (elle)</h3>
<p>
	Practica cuerdas desde hace años y da talleres inventados en distintos espacios. Le interesa la
	cuerda como juego y como forma de cuidado.
</p>
<h2 id="bloque-2">Bloque 2: suspensión parcial (demostración)</h2>
<p>
	Una demostración comentada, sin práctica de suspensión del público. Vas a poder preguntar todo lo
	que quieras.
</p>
<ul>
	<li>16:45 ARG · 16:45 UY · 14:45 COL</li>
	<li>Duración: 1 hora</li>
</ul>
<h3>Persona de Prueba Tres (ella)</h3>
<p>Hace performance con cuerdas y acompaña grupos de estudio. Este párrafo también es inventado.</p>
<h2 id="bloque-3">Bloque 3: charla y cierre</h2>
<p>Una ronda para compartir cómo nos sentimos, con mate y algo rico.</p>
<ul>
	<li>¿Qué te llevás de hoy?</li>
	<li>¿Qué te gustaría practicar en la próxima edición?</li>
	<li>¿Cómo cuidamos el espacio entre todes?</li>
</ul>
